// generate-pdf-data.js
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// --- 配置区 ---
// 您的 GitHub 用户名和仓库名
const GITHUB_USER = 'SAY683';
const GITHUB_REPO = 'Annals-of-the-Great-Simplicity';
// 需要扫描PDF的源文件夹 (相对于项目根目录)
const SOURCE_DIRS = ['Miscellanies']; // '.' 代表根目录（现暂且不展示）
// 最终生成的js数据文件要输出到哪里
const OUTPUT_FILE = path.join('Base', 'JS', 'pdf-data.js');
// -----------------

console.log('Starting PDF data generation...');

try {
    const commitHash = execSync('git rev-parse HEAD').toString().trim();
    console.log(`Using permanent commit hash: ${commitHash}`);

    const baseUrl = `https://raw.githubusercontent.com/${GITHUB_USER}/${GITHUB_REPO}/${commitHash}`;
    
    let allPdfFiles = [];

    SOURCE_DIRS.forEach(dir => {
        const sourcePath = path.resolve(__dirname, dir);
        if (!fs.existsSync(sourcePath)) return;

        console.log(`Scanning directory: ${sourcePath}`);
        const files = fs.readdirSync(sourcePath);

        const pdfsInDir = files
            .filter(file => path.extname(file).toLowerCase() === '.pdf')
            .map(file => {
                const title = path.basename(file, '.pdf');
                const remotePath = `${dir === '.' ? '' : dir + '/'}${encodeURIComponent(file)}`;
                
                return {
                    title: title,
                    remoteFile: `${baseUrl}/${remotePath}`,
                    localFile: `Miscellanies/${file}`
                };
            });
        
        allPdfFiles = allPdfFiles.concat(pdfsInDir);
    });

    const fileContent = `// This file is auto-generated by generate-pdf-data.js\n\nconst pdfFiles = ${JSON.stringify(allPdfFiles, null, 4)};`;

    fs.writeFileSync(OUTPUT_FILE, fileContent);
    console.log(`Successfully generated ${OUTPUT_FILE} with ${allPdfFiles.length} PDF entries.`);

} catch (error) {
    console.error('Error during PDF data generation:', error);
    process.exit(1);
}